package com.gathin.tvhome;

import static org.junit.Assert.assertEquals;
import static org.junit.Assert.assertNull;

import org.junit.Test;

/**
 * QrCode module for module, level M and mask 0. The version 4 code is the Python qrcode package's output for the
 * same text; for the version 2 one that package puts the digits in a numeric segment, so the expected code is this
 * encoder's own single byte segment, which OpenCV's QR reader decodes back to the address.
 */
public class QrCodeTest {
    private static String matrix(QrCode qr) {
        StringBuilder out = new StringBuilder();
        for (int y = 0; y < qr.size(); y++) {
            if (y > 0) out.append('|');
            for (int x = 0; x < qr.size(); x++) out.append(qr.dark(x, y) ? '1' : '0');
        }
        return out.toString();
    }

    @Test
    public void uploadAddressMatchesTheReferenceVersion2() {
        assertEquals("1111111001100001101111111|1000001011011111001000001|1011101000100001001011101|"
                + "1011101000010000001011101|1011101011110001101011101|1000001001110101101000001|"
                + "1111111010101010101111111|0000000001001101000000000|1010101001110110000010010|"
                + "0110100000100010001100001|0000001010111110101110111|1111000011100100111110010|"
                + "0010011010110111101101011|0011110101010010011101001|1000101010000010110110111|"
                + "0101010101110101011101010|1001011010001111111111000|0000000010111110100011111|"
                + "1111111001111101101010011|1000001000101101100011010|1011101011111110111110000|"
                + "1011101001010111110010100|1011101011101001110011001|1000001001100100110011010|"
                + "1111111011000110111100011", matrix(QrCode.encode("http://192.168.1.50:8642")));
    }

    @Test
    public void longerTextMatchesTheReferenceVersion4WithTwoBlocks() {
        assertEquals("111111100111101100010111101111111|100000101001010100011111001000001|"
                + "101110100010000010010000101011101|101110100001010100100011001011101|"
                + "101110101011000000110111101011101|100000100000010001111011001000001|"
                + "111111101010101010101010101111111|000000000110011011111101100000000|"
                + "101010100001010101011110000010010|111000000010000010100110001100011|"
                + "100011100011110000101100101100111|011011011101000111000100111010000|"
                + "111100111001100101001101001101010|001010000110000101000100111000101|"
                + "010001110111110000100000101110111|100010011000100101000111000000010|"
                + "010011110001000011000111101000000|010000010010000001000010001100011|"
                + "010011101001111010001100110100101|011011000010011111111111000010000|"
                + "001101101100001011000100011001011|000000011001000110000010101000111|"
                + "101001110110001110001110001101011|010101011011011011001101110000000|"
                + "101000100001011111000110111110000|000000001010101011000110100011011|"
                + "111111100110010001101111101010111|100000100100100101101101100011001|"
                + "101110101111100011000110111111011|101110100001011100001001110110101|"
                + "101110101000110001000011000010001|100000100000110001111101100110010|"
                + "111111101001010111010111101000011",
                matrix(QrCode.encode("http://10.0.0.5:8642/upload-page-longer-text-for-v3-check")));
    }

    @Test
    public void tooLongForVersion6IsNull() {
        StringBuilder text = new StringBuilder();
        for (int i = 0; i < 120; i++) text.append('a');
        assertNull(QrCode.encode(text.toString()));
    }
}
